import { describe, expect, it } from "vitest";
import { getMondayOfWeek } from "./foodQueries";

describe("getMondayOfWeek", () => {
	it("TC-28: для понедельника возвращает тот же день", () => {
		// 2026-05-11 — понедельник
		expect(getMondayOfWeek("2026-05-11")).toBe("2026-05-11");
	});

	it("TC-29: для воскресенья возвращает понедельник предыдущей недели", () => {
		// 2026-05-17 — воскресенье; понедельник этой недели = 2026-05-11
		expect(getMondayOfWeek("2026-05-17")).toBe("2026-05-11");
	});

	it("TC-30: для среды возвращает понедельник этой недели", () => {
		// 2026-05-13 — среда; понедельник = 2026-05-11
		expect(getMondayOfWeek("2026-05-13")).toBe("2026-05-11");
	});

	it("TC-31: корректно переходит через смену месяца", () => {
		// 2026-06-02 — вторник; понедельник = 2026-06-01
		expect(getMondayOfWeek("2026-06-02")).toBe("2026-06-01");
		// 2026-03-04 — среда; понедельник = 2026-03-02
		expect(getMondayOfWeek("2026-03-04")).toBe("2026-03-02");
	});
});
